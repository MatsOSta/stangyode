import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const load = async (name) => JSON.parse(await readFile(resolve(repo, `atlas/data/${name}`), 'utf8'));
const radar = await load('frontier-radar.json');
const discovery = await load('github-discovery.json');
const line = (value) => String(value).replaceAll('\n', ' ');
const bilingual = (value) => `${line(value.en)} / ${line(value.ja)}`;
const adoptionById = new Map(radar.adoption.map((item) => [item.signalId, item]));

const sections = radar.signals.map((signal) => {
  const adoption = adoptionById.get(signal.id);
  const history = signal.history.map((item) => `  - ${item.date}: ${bilingual(item.event)}`).join('\n');
  const tradeoffs = signal.tradeoffs.map((item) => `  - ${bilingual(item)}`).join('\n');
  return [
    `### ${bilingual(signal.name)}`,
    `- Adoption stage / 導入段階: ${adoption.stage.toUpperCase()} (${adoption.score}/100)`,
    `- Scores / スコア: frontier ${signal.scores.frontier}, fit ${signal.scores.fit}, confidence ${signal.scores.confidence}`,
    `- Recommendation / 推奨: ${bilingual(signal.recommendation)}`,
    `- Compatibility / 互換性: ${signal.compatibility.status.toUpperCase()} — ${bilingual(signal.compatibility.rationale)}`,
    `- Trade-offs / トレードオフ:\n${tradeoffs}`,
    `- Provenance / 来歴: ${signal.provenance.kind}; ${signal.provenance.status}; ${signal.provenance.collectedAt}`,
    `- History / 履歴:\n${history}`,
  ].join('\n');
}).join('\n\n');

const queries = discovery.queries.map((query) => `- ${query.candidateId}: ${query.query} (${query.state})`).join('\n');
export const markdown = [
  `# ${bilingual(radar.meta.title)}`,
  '',
  `Snapshot / スナップショット: ${radar.meta.snapshot}`,
  '',
  bilingual(radar.meta.purpose),
  '',
  `> ${bilingual(radar.meta.evidencePolicy)}`,
  '',
  '## Signals / シグナル',
  '',
  sections,
  '',
  '## GitHub discovery input / GitHub発見入力',
  '',
  bilingual(discovery.policy),
  '',
  `Provider / プロバイダー: ${discovery.provider}; mode / モード: ${discovery.mode}; live fetch / ライブ取得: ${discovery.liveFetch ? 'yes' : 'no'}`,
  '',
  queries,
  '',
  `Collected signals / 収集済みシグナル: ${discovery.signals.length}`,
  '',
  'Generated by atlas/scripts/render-frontier-briefing.mjs; deterministic for the checked-in inputs.',
  '',
].join('\n');

const output = resolve(repo, 'atlas/artifacts/frontier-radar-briefing.md');
await mkdir(dirname(output), { recursive: true });
if (process.argv.includes('--write')) await writeFile(output, markdown, 'utf8');
if (process.argv.includes('--write')) console.log(`Generated ${output}`);
